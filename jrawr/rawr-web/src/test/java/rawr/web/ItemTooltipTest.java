package rawr.web;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.mock.web.MockHttpSession;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;
import org.springframework.web.util.HtmlUtils;
import rawr.base.items.Item;
import rawr.base.items.ItemCache;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Offline MockMvc tests for item icons and the htmx tooltip endpoint: icon URLs come from the
 * configurable base (no image is ever fetched), sources come from the loaded ItemSource.xml, and
 * slot tooltips include the equipped instance's enchant and gems. Set-bonus lines show the prose
 * of the committed {@code set-bonus-text.json} artifact (generated by tools/set-bonus-gen).
 */
@SpringBootTest
@AutoConfigureMockMvc
class ItemTooltipTest {
    private static final Path REPO_ROOT =
            Paths.get(System.getProperty("jrawr.repoRoot", "../..")).toAbsolutePath().normalize();
    private static final String ICON_SITE = "https://icons.test";
    // Unknown host -> AoWoW layout (see ItemIconService.LAYOUT_RULES).
    private static final String ICON_BASE = ICON_SITE + "/static/images/wow/icons/large/";
    // Real T10 Mage set-bonus prose from the generated artifact (set-bonus-text.json).
    private static final String T10_2PC = "Your Hot Streak, Missile Barrage, and Brain Freeze talents "
            + "also grant you 12% haste for 5 sec when the effect of the talent is consumed.";
    private static final String T10_4PC = "Your Mirror Image ability also causes you to deal 18% "
            + "additional damage for 30 sec.";

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private DataBootstrap dataBootstrap;

    @DynamicPropertySource
    static void properties(DynamicPropertyRegistry registry) {
        registry.add("jrawr.data-dir",
                () -> REPO_ROOT.resolve("jrawr/data").toString());
        registry.add("jrawr.icon-base-url", () -> ICON_SITE);
    }

    @BeforeEach
    void loadData() {
        dataBootstrap.load();
    }

    @Test
    void baseItemTooltipShowsNameIdSourceAndIcon() throws Exception {
        Item item = ItemCache.findItemById(50732);
        assertThat(item).as("Bloodsurge in the item cache").isNotNull();

        MvcResult result = mockMvc.perform(get("/item-tooltip").param("id", "50732"))
                .andExpect(status().isOk())
                .andReturn();
        String body = html(result);

        assertThat(body)
                .contains("Bloodsurge")
                .contains("Item ID 50732")
                .contains("Spell Power")
                .contains("Icecrown Citadel (25)")
                .contains("The Lich King")
                .contains("src=\"" + ICON_BASE + item.getIconPath() + ".jpg");
        assertThat(body).doesNotContain("<html");
    }

    @Test
    void itemPickerRowsContainQualityIcons() throws Exception {
        MvcResult result = mockMvc.perform(get("/items").param("slot", "Head"))
                .andExpect(status().isOk())
                .andReturn();
        String body = html(result);

        assertThat(body)
                .contains("class=\"item-icon\"")
                .contains("src=\"" + ICON_BASE)
                .contains("hx-get=\"/item-tooltip?id=")
                .contains("class=\"item-row tip-right\"")
                .contains("class=\"item-tooltip\"")
                .contains("hx-target=\"find .item-tooltip\"")
                .contains("hx-trigger=\"mouseenter once, focusin once\"");
        assertThat(body).doesNotContain("<html");
    }

    @Test
    void paperdollSlotRendersIconWithSlotTooltipUrl() throws Exception {
        MockHttpSession session = importFixture("arcane_277_raid.xml");
        MvcResult result = mockMvc.perform(get("/").session(session))
                .andExpect(status().isOk())
                .andReturn();
        String body = html(result);

        assertThat(body)
                .contains("class=\"item-icon\"")
                .contains("src=\"" + ICON_BASE + "inv_helmet_150black.jpg")
                .contains("hx-get=\"/item-tooltip?id=51281&amp;slot=Head\"")
                .contains("class=\"item-tooltip\"")
                .contains("hx-target=\"find .item-tooltip\"")
                .contains("hx-trigger=\"mouseenter once, focusin once\"");
        assertThat(body)
                .contains("class=\"slot is-filled tip-right\"") // Head, left column
                .contains("class=\"slot is-filled tip-left\"")  // Hands, right column
                .contains("class=\"slot is-filled tip-top\"");  // Main Hand, bottom row
        assertThat(count(body, "tip-right")).as("left column opens right").isEqualTo(8);
        assertThat(count(body, "tip-left")).as("right column opens left").isEqualTo(8);
        assertThat(count(body, "tip-top")).as("bottom row opens above").isEqualTo(3);
    }

    @Test
    void slotTooltipIncludesEnchantAndGemNamesOfTheInstance() throws Exception {
        MockHttpSession session = importFixture("arcane_277_raid.xml");

        MvcResult result = mockMvc.perform(get("/item-tooltip")
                        .param("id", "51281")
                        .param("slot", "Head")
                        .session(session))
                .andExpect(status().isOk())
                .andReturn();
        String body = html(result);

        assertThat(body)
                .contains("Sanctified Bloodmage Hood")
                .contains("tt-extras tt-enchant")
                .contains("Arcanum of Burning Mysteries")
                .contains("30 Spell Power")
                .contains("20 Crit Rating")
                .contains("tt-gem-lines")
                .contains("tt-gem", "tt-gem-dot", "tt-gem-name", "tt-gem-stats", "gem-meta")
                .contains("Chaotic Skyflare Diamond")
                .contains("21 Crit Rating")
                .contains("Purified Dreadstone")
                .contains("gem-purple")
                .contains("tt-socket-list", "socket-meta")
                .contains("tt-socket-bonus is-active")
                .contains("Socket bonus: 9 Spell Power (active)")
                .contains("Item ID 51281");
    }

    // ------------------------------------------------------------------ set bonuses

    @Test
    void baseItemTooltipShowsGeneratedSetBonusProseWithoutActiveMarkers() throws Exception {
        MvcResult result = mockMvc.perform(get("/item-tooltip").param("id", "51281"))
                .andExpect(status().isOk())
                .andReturn();
        String body = unescaped(result);

        assertThat(body)
                .contains("Bloodmage's Regalia")
                .contains("(2) Set: " + T10_2PC)
                .contains("(4) Set: " + T10_4PC);
        assertThat(body)
                .doesNotContain("is-active")
                .doesNotContain("is-inactive")
                .doesNotContain("(if equipped)")
                .doesNotContain("bonuses active");
    }

    @Test
    void slotTooltipMarksSetBonusesActiveFromFourEquippedPieces() throws Exception {
        MockHttpSession session = importFixture("arcane_277_raid.xml");

        MvcResult result = mockMvc.perform(get("/item-tooltip")
                        .param("id", "51281")
                        .param("slot", "Head")
                        .session(session))
                .andExpect(status().isOk())
                .andReturn();
        String body = unescaped(result);

        assertThat(body)
                .contains("Set: Bloodmage's Regalia (5/5, 2 bonuses active)")
                .contains("class=\"is-active\"")
                .contains("(4) Set: " + T10_4PC);
        assertThat(body).doesNotContain("is-inactive").doesNotContain("(if equipped)");
    }

    @Test
    void slotTooltipMarksFourPieceBonusInactiveWithOnlyThreePieces() throws Exception {
        MockHttpSession session = importFixture("fire_t10_2pc_procs.xml");

        MvcResult result = mockMvc.perform(get("/item-tooltip")
                        .param("id", "51281")
                        .param("slot", "Head")
                        .session(session))
                .andExpect(status().isOk())
                .andReturn();
        String body = unescaped(result);

        assertThat(body)
                .contains("Set: Bloodmage's Regalia (3/4, 1 bonus active)")
                .contains("(2) Set: " + T10_2PC)
                .contains("(4) Set: " + T10_4PC);
        assertThat(body).contains("is-active").contains("is-inactive");
    }

    @Test
    void pickerTooltipSimulatesEquippingIntoEmptySlot() throws Exception {
        MockHttpSession session = importFixture("arcane_blank.xml");

        MvcResult result = mockMvc.perform(get("/item-tooltip")
                        .param("id", "51281")
                        .param("slot", "Head")
                        .param("picker", "true")
                        .session(session))
                .andExpect(status().isOk())
                .andReturn();
        String body = unescaped(result);

        assertThat(body)
                .contains("Bloodmage's Regalia")
                .contains("Set: Bloodmage's Regalia (1/4, 0 bonuses active)")
                .contains("(if equipped)")
                .contains("(2) Set: " + T10_2PC)
                .contains("class=\"is-inactive\"");
        assertThat(body).doesNotContain("is-active");
    }

    @Test
    void pickerTooltipSimulatesReplacingASameSetItemAndKeepsBonusesActive() throws Exception {
        MockHttpSession session = importFixture("arcane_277_raid.xml");

        MvcResult result = mockMvc.perform(get("/item-tooltip")
                        .param("id", "51281")
                        .param("slot", "Head")
                        .param("picker", "true")
                        .session(session))
                .andExpect(status().isOk())
                .andReturn();
        String body = unescaped(result);

        assertThat(body)
                .contains("Set: Bloodmage's Regalia (5/5, 2 bonuses active)")
                .contains("(if equipped)")
                .contains("class=\"is-active\"");
        assertThat(body).doesNotContain("is-inactive");
    }

    private MockHttpSession importFixture(String fixtureName) throws Exception {
        byte[] xml = Files.readAllBytes(REPO_ROOT.resolve("oracle/fixtures/mage/" + fixtureName));
        MockHttpSession session = new MockHttpSession();
        mockMvc.perform(multipart("/character")
                        .file(new MockMultipartFile("file", fixtureName, "text/xml", xml))
                        .param("model", "Mage")
                        .session(session))
                .andExpect(status().is3xxRedirection());
        return session;
    }

    private static String unescaped(MvcResult result) throws Exception {
        return HtmlUtils.htmlUnescape(html(result));
    }

    private static String html(MvcResult result) throws Exception {
        return result.getResponse().getContentAsString(StandardCharsets.UTF_8);
    }

    private static int count(String haystack, String needle) {
        int count = 0;
        int index = haystack.indexOf(needle);
        while (index >= 0) {
            count++;
            index = haystack.indexOf(needle, index + needle.length());
        }
        return count;
    }
}
