/**
 * Builds the item tooltip view model. For an equipped instance ({@code slot} requests) the stats
 * come from {@link ItemInstance#getTotalStats(Character)} so gems, socket bonus and enchant are
 * included; for a bare item ({@code id} requests) the base {@link Item#getStats()} is used.
 * Stat labels and value formatting follow the legacy ItemToolTip drawing code.
 *
 * <p>Set-bonus lines show the real WoW prose from the committed {@code set-bonus-text.json}
 * artifact (generated by {@code tools/set-bonus-gen}, DECISIONS #36), keyed by set name and
 * threshold; sets or thresholds missing from the artifact fall back to the bonus buff's name.
 */
@Service
public class ItemTooltipService {
    static final String SET_BONUS_TEXT_RESOURCE = "/set-bonus-text.json";

    private final ItemIconService icons;
    private final Map<String, Map<Integer, String>> setBonusText;

    @Autowired
    public ItemTooltipService(ItemIconService icons) {
        this(icons, loadSetBonusText());
    }

    ItemTooltipService(ItemIconService icons, Map<String, Map<Integer, String>> setBonusText) {
        this.icons = icons;
        this.setBonusText = setBonusText;
    }

    /** Loads the generated artifact once from the classpath; an absent file means no mappings. */
    static Map<String, Map<Integer, String>> loadSetBonusText() {
        try (InputStream in = ItemTooltipService.class.getResourceAsStream(SET_BONUS_TEXT_RESOURCE)) {
            if (in == null) {
                return Map.of();
            }
            Map<String, Map<String, String>> raw = JsonMapper.builder().build()
                    .readValue(in, new TypeReference<Map<String, Map<String, String>>>() {
                    });
            Map<String, Map<Integer, String>> result = new HashMap<String, Map<Integer, String>>();
            for (Map.Entry<String, Map<String, String>> entry : raw.entrySet()) {
                Map<Integer, String> thresholds = new HashMap<Integer, String>();
                for (Map.Entry<String, String> threshold : entry.getValue().entrySet()) {
                    thresholds.put(Integer.valueOf(threshold.getKey()), threshold.getValue());
                }
                result.put(entry.getKey(), thresholds);
            }
            return Map.copyOf(result);
        } catch (Exception e) {
            throw new IllegalStateException("Failed to load " + SET_BONUS_TEXT_RESOURCE, e);
        }
    }

    /** Base item tooltip (no gems/enchant/socket bonus of an instance). */
    public ItemTooltip forItem(int itemId) {
        Item item = ItemCache.findItemById(itemId);
        return item == null ? null : build(item, null, null, null);
    }

    /** Tooltip for an item object that may not be in the cache yet (editor preview). */
    public ItemTooltip forItem(Item item) {
        return item == null ? null : build(item, null, null, null);
    }

    /** Tooltip for the item equipped in {@code slot} of the given character. */
    public ItemTooltip forSlot(Character character, CharacterSlot slot) {
        ItemInstance instance = character.get(slot);
        if (instance == null || instance.getItem() == null) {
            return null;
        }
        return build(instance.getItem(), instance, character, null);
    }

    /**
     * Picker tooltip: the candidate {@code itemId} rendered with base item stats, but the set
     * bonus block simulates equipping it into {@code slot} of the session character.
     */
    public ItemTooltip forPicker(Character character, CharacterSlot slot, int itemId) {
        Item item = ItemCache.findItemById(itemId);
        return item == null ? null : build(item, null, character, slot);
    }

    /**
     * Comparison-chart tooltip: the exact gemmed/enchanted candidate instance, with set bonuses
     * simulated for {@code slot} because the candidate is not equipped yet.
     */
    public ItemTooltip forInstance(Character character, CharacterSlot slot, String gemmedId) {
        if (gemmedId == null || gemmedId.isBlank()) {
            return null;
        }
        ItemInstance instance;
        try {
            instance = new ItemInstance(gemmedId);
        } catch (NumberFormatException e) {
            return null;
        }
        return instance.getItem() == null ? null : build(instance.getItem(), instance, character, slot);
    }

    private ItemTooltip build(Item item, ItemInstance instance, Character character, CharacterSlot pickerSlot) {
        Stats stats = instance != null && character != null
                ? instance.getTotalStats(character)
                : item.getStats();

        List<StatLine> statLines = statLines(stats);
        List<ItemTooltip.EffectLine> effects = effectLines(item.getStats());

        List<GemLine> gems = new ArrayList<GemLine>();
        String enchantName = null;
        List<String> enchantStats = new ArrayList<String>();
        if (instance != null) {
            for (int index = 1; index <= 3; index++) {
                Item gem = instance.getGem(index);
                if (gem != null && gem.getName() != null) {
                    ItemSlot color = gem.getSlot();
                    gems.add(new GemLine(gem.getName(), gem.getStats().toString(),
                            color == null ? "none" : color.name().toLowerCase(Locale.ROOT)));
                }
            }
            if (instance.getEnchantId() != 0) {
                Enchant enchant = Enchant.findEnchant(instance.getEnchantId(), instance.getSlot(), character);
                if (enchant != null && enchant.id == instance.getEnchantId()
                        && instance.isEnchantEligible(enchant)) {
                    enchantName = enchant.name;
                    enchantStats.addAll(enchantStatTexts(enchant));
                }
            }
        }

        List<SocketLine> sockets = new ArrayList<SocketLine>();
        addSocket(sockets, item.getSocketColor1());
        addSocket(sockets, item.getSocketColor2());
        addSocket(sockets, item.getSocketColor3());
        String socketBonusText = joinTexts(statLines(item.getSocketBonus()));
        Boolean socketBonusActive = instance == null ? null : instance.matchesSocketBonus();

        SetInfo setInfo = setInfo(item.getSetName(), character, pickerSlot);

        Source source = item.getId() >= ItemEditorService.CUSTOM_ITEM_ID_MIN
                ? new Source("Custom", "Custom item") : source(item);

        return new ItemTooltip(
                item.getName(),
                item.getQuality().name().toLowerCase(Locale.ROOT),
                item.getItemLevel(),
                slotText(item),
                item.getSetName(),
                statLines,
                effects,
                enchantName,
                enchantStats,
                gems,
                sockets,
                socketBonusText,
                socketBonusActive,
                setInfo.lines,
                setInfo.summary,
                setInfo.simulated,
                item.getId(),
                source.kind,
                source.description,
                icons.url(item.getIconPath()),
                icons.initials(item.getName()));
    }

    /**
     * Builds the set bonus block. Without a character the lines carry no active marker; with one,
     * the equipped count (or the picker's simulated count) decides which thresholds are active.
     */
    private SetInfo setInfo(String setName, Character character, CharacterSlot pickerSlot) {
        if (setName == null || setName.isEmpty()) {
            return SetInfo.EMPTY;
        }
        Buff[] bonuses = Buff.getSetBonuses(setName);
        if (bonuses == null || bonuses.length == 0) {
            return SetInfo.EMPTY;
        }
        List<Buff> sorted = new ArrayList<Buff>(Arrays.asList(bonuses));
        sorted.sort(Comparator.comparingInt(bonus -> bonus.setThreshold));

        int totalPieces = 0;
        for (Buff bonus : sorted) {
            totalPieces = Math.max(totalPieces, bonus.setThreshold);
        }

        List<SetBonusLine> lines = new ArrayList<SetBonusLine>();
        if (character == null) {
            for (Buff bonus : sorted) {
                lines.add(new SetBonusLine(bonus.setThreshold, setBonusDescription(setName, bonus), null));
            }
            return new SetInfo(lines, null, false);
        }

        boolean simulated = pickerSlot != null;
        int equipped = simulated
                ? simulatedSetCount(character, pickerSlot, setName)
                : equippedSetCount(character, setName);
        // The buff data only knows the bonus thresholds, not the true set size; never show a
        // denominator below the equipped count (e.g. 5 equipped T10 pieces vs a 4-piece threshold).
        totalPieces = Math.max(totalPieces, equipped);

        int activeCount = 0;
        for (Buff bonus : sorted) {
            boolean active = equipped >= bonus.setThreshold;
            if (active) {
                activeCount++;
            }
            lines.add(new SetBonusLine(bonus.setThreshold, setBonusDescription(setName, bonus), active));
        }
        String summary = "Set: " + setName + " (" + equipped + "/" + totalPieces + ", "
                + activeCount + (activeCount == 1 ? " bonus active)" : " bonuses active)");
        return new SetInfo(lines, summary, simulated);
    }

    /** Equipped count of a set from the character's last set-bonus recalculation. */
    private static int equippedSetCount(Character character, String setName) {
        Map<String, Integer> counts = character.getSetBonusCount();
        if (counts != null) {
            Integer count = counts.get(setName);
            return count == null ? 0 : count;
        }
        return countEquipped(character, setName);
    }

    /**
     * Counts the set after simulating the picker item in {@code pickerSlot}: a same-set item in
     * that slot only replaces itself (count unchanged), a different or empty slot adds one.
     */
    private static int simulatedSetCount(Character character, CharacterSlot pickerSlot, String setName) {
        int count = equippedSetCount(character, setName);
        ItemInstance current = character.get(pickerSlot);
        Item currentItem = current == null ? null : current.getItem();
        String currentSet = currentItem == null ? null : currentItem.getSetName();
        return setName.equals(currentSet) ? count : count + 1;
    }

    private static int countEquipped(Character character, String setName) {
        int count = 0;
        for (CharacterSlot slot : CharacterSlot.values()) {
            ItemInstance instance = character.get(slot);
            if (instance != null && instance.getItem() != null
                    && setName.equals(instance.getItem().getSetName())) {
                count++;
            }
        }
        return count;
    }

    /** Set-bonus prose for (setName, threshold); the bonus buff's name when not mapped. */
    private String setBonusDescription(String setName, Buff bonus) {
        Map<Integer, String> thresholds = setBonusText.get(setName);
        if (thresholds != null) {
            String text = thresholds.get(bonus.setThreshold);
            if (text != null && !text.isBlank()) {
                return text;
            }
        }
        return bonus.name;
    }

    /** Enchant details: one line per stat plus one line per special effect. */
    private static List<String> enchantStatTexts(Enchant enchant) {
        List<String> lines = new ArrayList<String>();
        for (StatLine line : statLines(enchant.stats)) {
            lines.add(line.text());
        }
        for (SpecialEffect effect : enchant.stats.specialEffects()) {
            lines.add(effect.toString());
        }
        return lines;
    }

    private static List<ItemTooltip.EffectLine> effectLines(Stats stats) {
        List<ItemTooltip.EffectLine> lines = new ArrayList<ItemTooltip.EffectLine>();
        for (SpecialEffect effect : stats.specialEffects()) {
            if (effect == null) {
                continue;
            }
            String label = effect.getTrigger() == Trigger.Use ? "Use" : "Equip";
            lines.add(new ItemTooltip.EffectLine(label, effect.toString()));
        }
        return lines;
    }

    private static List<StatLine> statLines(Stats stats) {
        List<StatLine> lines = new ArrayList<StatLine>();
        for (Stats.StatProperty property : Stats.PROPERTY_INFO) {
            if ( property.category() == null || "Deprecated".equals(property.category())) {
                continue;
            }
            float value = property.accessor().get(stats);
            if (value == 0f || Float.isNaN(value) || Float.isInfinite(value)) {
                continue;
            }
            lines.add(new StatLine(
                    formatValue(value, property.percentage()),
                    property.displayName() != null ? property.displayName() : spaceCamel(property.name())));
        }
        return lines;
    }

    private static void addSocket(List<SocketLine> sockets, ItemSlot color) {
        if (color == null || color == ItemSlot.None) {
            return;
        }
        sockets.add(new SocketLine(color.name().toLowerCase(Locale.ROOT), spaceCamel(color.name()) + " socket"));
    }

    private static String joinTexts(List<StatLine> lines) {
        StringBuilder text = new StringBuilder();
        for (StatLine line : lines) {
            if (text.length() > 0) {
                text.append(", ");
            }
            text.append(line.text());
        }
        return text.length() == 0 ? null : text.toString();
    }

    /** Legacy ItemToolTip: percentage stats are shown multiplied by 100, rounded to 2 decimals. */
    private static String formatValue(float value, boolean percentage) {
        double scaled = percentage ? value * 100.0 : value;
        double rounded = Math.rint(scaled * 100.0) / 100.0;
        String text = String.format(Locale.ROOT, "%.2f", rounded);
        if (text.indexOf('.') >= 0) {
            text = text.replaceAll("0+$", "").replaceAll("\\.$", "");
        }
        return text;
    }

    private static String spaceCamel(String name) {
        return name.replaceAll("([A-Z])", " $1").trim();
    }

    private static String slotText(Item item) {
        String slot = spaceCamel(item.getSlot().name());
        if (item.getType() == null || item.getType() == ItemType.None) {
            return slot;
        }
        return slot + " · " + spaceCamel(item.getType().name());
    }

    private static Source source(Item item) {
        for (ItemLocation location : item.getLocationInfo()) {
            if (location == null) {
                continue;
            }
            String description = cleanDescription(location.getDescription());
            // The legacy vendor parse can leave an empty "Sold by <null> at <null>" behind.
            if (description != null && description.equals("Sold by at")) {
                description = null;
            }
            return new Source(kindName(location.getSource()), description);
        }
        return new Source("Unknown", null);
    }

    private static String cleanDescription(String description) {
        if (description == null) {
            return null;
        }
        String cleaned = description.replaceAll("\\bnull\\b", "").replaceAll("\\s+", " ").trim();
        return cleaned.isEmpty() ? null : cleaned;
    }

    private static String kindName(ItemSource source) {
        return switch (source) {
            case Vendor -> "Vendor";
            case Faction -> "Faction";
            case PVP -> "PvP";
            case Crafted -> "Crafted";
            case WorldDrop -> "World drop";
            case StaticDrop -> "Drop";
            case Quest -> "Quest";
            case Container -> "Container";
            case None -> "No source";
            case NotFound, Unknown -> "Unknown";
        };
    }

    private static final class Source {
        final String kind;
        final String description;

        Source(String kind, String description) {
            this.kind = kind;
            this.description = description;
        }
    }

    /** Set block data: the bonus lines plus the optional "(equipped/total, N active)" header. */
    private record SetInfo(List<SetBonusLine> lines, String summary, boolean simulated) {
        static final SetInfo EMPTY = new SetInfo(List.of(), null, false);
    }
}
