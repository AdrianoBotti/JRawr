import rawr.base.stats.StatConversion;
import rawr.base.stats.Stats;

public abstract class Spell {
    protected float minHeal = 0f;

    public float getMinHeal() {
        return healModifier * (minHeal + spellPower * coefDH);
    }

    public float getBaseMinHeal() {
        return minHeal;
    }

    protected float maxHeal = 0f;

    public float getMaxHeal() {
        return healModifier * (maxHeal + spellPower * coefDH);
    }

    public float getBaseMaxHeal() {
        return maxHeal;
    }

    protected int numberOfCasts = 1;

    public float getNumberOfCasts() {
        return numberOfCasts;
    }

    public float castTime = 0f;
    public float castTimeBeforeHaste = 0f;

    public float getCastTime() {
        if (castTime > gcd) {
            return numberOfCasts * castTime;
        } else if (gcd > 1) {
            return numberOfCasts * gcd;
        } else {
            return numberOfCasts;
        }
    }

    public float gcd = 1.5f;
    public float gcdBeforeHaste = 1.5f;

    protected float manaCost = 0f;

    public float getManaCost() {
        return manaCost * numberOfCasts;
    }

    public float coefDH = 0f;
    public float coefHoT = 0f;
    protected float spellPower = 0f;

    public float getSpellPower() {
        return spellPower;
    }

    public float speed = 1f;
    protected float critModifier = 1.5f;

    public float getCritModifier() {
        return critModifier;
    }

    protected float critPercent = 0f;

    public float getCritPercent() {
        return critPercent;
    }

    protected float critHoTPercent = 0f;

    public float getCritHoTPercent() {
        return critHoTPercent;
    }

    protected float periodicTick = 0f;
    protected float periodicTicks = 0f;

    public float getPeriodicTicks() {
        return periodicTicks;
    }

    protected float periodicTickTimeBeforeHaste = 3f;
    protected float periodicTickTime = 3f;

    public float getPeriodicTickTime() {
        return periodicTickTime;
    }

    protected float extraHealing = 0f;
    protected float healModifier = 1f;

    public float getAverageHealing() {
        return healModifier * (extraHealing + (minHeal + maxHeal) / 2f + getSpellPower() * coefDH);
    }

    /** Direct heal component of this spell. */
    public float getAverageHealingwithCrit() {
        return (getAverageHealing() * (100f - getCritPercent()) + (getAverageHealing() * getCritModifier()) * getCritPercent()) / 100f;
    }

    public float getPeriodicTick() {
        return healModifier * (periodicTick + spellPower * coefHoT);
    }

    public float getPeriodicTickwithCrit() {
        return (getPeriodicTick() * (100f - getCritHoTPercent()) + (getPeriodicTick() * getCritModifier()) * getCritHoTPercent()) / 100f;
    }

    /** Total healing generated by this spell, includes base, crit and HoT effects. */
    public float getTotalAverageHealing() {
        return (getAverageHealingwithCrit() + getPeriodicTickwithCrit() * getPeriodicTicks());
    }

    public float getDuration() {
        return getPeriodicTicks() * getPeriodicTickTime();
    }

    // HPS: The healing per second you will get when either chaincasting or refreshing perfectly
    // HPS_DH: Direct Healing divided per cast time
    // HPS_HOT: Rate at which HoT healing is applied
    public float getHPS() {
        return getTotalAverageHealing() / Math.max(getCastTime(), getDuration());
    }

    public float getHPS_DH() {
        return getAverageHealingwithCrit() / Math.max(getCastTime(), getDuration());
    }

    public float getHPS_HOT() {
        return periodicTickTime > 0 ? getPeriodicTickwithCrit() / periodicTickTime : 0;
    }

    public float getHPM() {
        return getTotalAverageHealing() / getManaCost();
    }

    public float getHPM_DH() {
        return getAverageHealingwithCrit() / getManaCost();
    }

    public float getHPM_HOT() {
        return getPeriodicTickwithCrit() * getPeriodicTicks() / getManaCost();
    }

    // Healing per cast time, considers direct healing and HoT parts.
    public float getHPCT() {
        return getTotalAverageHealing() / getCastTime();
    }

    public float getHPCT_DH() {
        return getAverageHealingwithCrit() / getCastTime();
    }

    public float getHPCT_HOT() {
        return getPeriodicTickwithCrit() * getPeriodicTicks() / getCastTime();
    }

    public float getHPSPM() {
        return getHPS() / getManaCost();
    }

    public float getHPSPM_DH() {
        return getHPS_DH() / getManaCost();
    }

    public float getHPSPM_HOT() {
        return getHPS_HOT() / getManaCost();
    }

    public float getHPCTPM() {
        return getHPCT() / getManaCost();
    }

    public float getHPCTPM_DH() {
        return getHPCT_DH() / getManaCost();
    }

    public float getHPCTPM_HOT() {
        return getHPCT_HOT() / getManaCost();
    }

    public void applyStats(Stats stats) {
        speed = (1 + StatConversion.getSpellHasteFromRating(stats.getHasteRating())) * (1 + stats.getSpellHaste());
        critModifier = 1.5f * (1f + stats.getBonusCritHealMultiplier());
        healModifier = (1f + stats.getBonusHealingDoneMultiplier());
        extraHealing = stats.getBonusHealingReceived();
        applyHaste();
    }

    protected void applyHaste() {
        gcd = gcdBeforeHaste / speed;
        if (gcd < 1f) {
            gcd = 1f;
        }
        castTime = (float) TreeFormat.round(castTimeBeforeHaste / speed, 4);
    }

    protected void applyHasteToPeriodicTickTime() {
        // Does Nature's Grace affect the duration of Rejuvenate?
        // It says: "casting speed" so I expect not...
        periodicTickTime = periodicTickTimeBeforeHaste / speed;
    }

    @Override
    public String toString() {
        return "" + TreeFormat.roundToString(getAverageHealingwithCrit(), 0) + "*" + TreeFormat.roundToString(getMinHeal(), 0) + " - " + TreeFormat.roundToString(getMaxHeal(), 0) + " normal\n"
                + TreeFormat.roundToString(getMinHeal() * getCritModifier(), 0) + " - " + TreeFormat.roundToString(getMaxHeal() * getCritModifier(), 0) + " crit\n"
                + TreeFormat.roundToString(getCritPercent(), 2) + "% crit chance\n"
                + (getPeriodicTick() > 0 ? TreeFormat.roundToString(getPeriodicTick(), 0) + " every " + TreeFormat.roundToString(getPeriodicTickTime(), 2) + " s." : "");
    }

}

class HealingTouch extends Spell {
        protected float manaCostModifier = 1f;
        protected float extraCritPercent = 0f;
        protected float extraCritModifier = 0f;

        public HealingTouch(rawr.base.character.Character character, Stats calculatedStats) {
            CalculationOptionsTree calcOpts = (CalculationOptionsTree) character.getCalculationOptions();

            // Base values
            castTimeBeforeHaste = 3f;
            coefDH = 1.62f;
            minHeal = 3750f;
            maxHeal = 4428f;

            calculateTalents(character.getDruidTalents(), calcOpts);

            // Glyph of Healing Touch
            if (character.getDruidTalents().isGlyphOfHealingTouch()) {
                castTimeBeforeHaste -= 1.5f;
                manaCostModifier *= 1 - 0.25f;
                minHeal *= 1 - 0.5f;
                maxHeal *= 1 - 0.5f;
                coefDH *= 1 - 0.5f;
            }

            applyStats(calculatedStats);
        }

        @Override
        public void applyStats(Stats stats) {
            super.applyStats(stats);
            spellPower = stats.getSpellPower() + stats.getHealingTouchFinalHealBonus();
            critPercent = stats.getSpellCrit() + extraCritPercent;
            critModifier += extraCritModifier;
            manaCost = 0.33f * TreeConstants.BaseMana - stats.getSpellsManaReduction();
            manaCost *= manaCostModifier;
        }

        private void calculateTalents(rawr.base.talents.DruidTalents druidTalents, CalculationOptionsTree calcOpts) {
            manaCostModifier *= 1 - (druidTalents.getMoonglow() * 0.03f + druidTalents.getTranquilSpirit() * 0.02f);

            castTimeBeforeHaste -= 0.1f * druidTalents.getNaturalist();

            extraCritPercent += 2f * druidTalents.getNaturesMajesty();

            // Living Seed, 30% seed, 33% * points spend (1/3)
            extraCritModifier = 0.1f * druidTalents.getLivingSeed() * calcOpts.getCurrent().getLivingSeedEfficiency() / 100f;

            // 6% chance to get Omen of Clarity...
            manaCostModifier *= 1 - 0.06f * druidTalents.getOmenOfClarity();

            minHeal *=
                    (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            maxHeal *=
                    (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            coefDH += (0.2f * druidTalents.getEmpoweredTouch());

            coefDH *=
                    (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());
        }
    }

class Regrowth extends Spell {
        protected float manaCostModifier = 1f;
        protected float extraCritPercent = 0f;
        protected float extraCritModifier = 0f;

        public Regrowth(rawr.base.character.Character character, Stats stats) {
            initializeRegrowth(character, stats);
        }

        public Regrowth(rawr.base.character.Character character, Stats stats, boolean withRegrowthActive, boolean clipIfGlyphed) {
            initializeRegrowth(character, stats);

            if (withRegrowthActive && character.getDruidTalents().isGlyphOfRegrowth()) {
                minHeal *= 1.2f;
                maxHeal *= 1.2f;
                periodicTick *= 1.2f;
                coefDH *= 1.2f;
                coefHoT *= 1.2f;

                if (clipIfGlyphed) {
                    periodicTicks--;
                }
            }
        }

        private void initializeRegrowth(rawr.base.character.Character character, Stats stats) {
            CalculationOptionsTree calcOpts = (CalculationOptionsTree) character.getCalculationOptions();

            // Base values
            castTimeBeforeHaste = 2f;
            coefDH = 0.54f;
            coefHoT = 1.316f / 7f;

            minHeal = 2234f;
            maxHeal = 2494f;
            periodicTick = 335f; // 2345 / 7
            periodicTicks = 7f;

            // Seems to apply before talents
            calculateTalents(character.getDruidTalents(), calcOpts);

            applyStats(stats);
        }

        @Override
        public void applyStats(Stats stats) {
            super.applyStats(stats);
            spellPower = stats.getSpellPower();
            critPercent = stats.getSpellCrit() + extraCritPercent;
            manaCost = 0.29f * TreeConstants.BaseMana - stats.getSpellsManaReduction();
            critModifier += extraCritModifier;
        }

        private void calculateTalents(rawr.base.talents.DruidTalents druidTalents, CalculationOptionsTree calcOpts) {
            periodicTicks += 2 * druidTalents.getNaturesSplendor();

            manaCostModifier *= (1 - 0.03f * druidTalents.getMoonglow() - 0.2f * druidTalents.getTreeOfLife());
            // 6% chance to get Omen of Clarity...
            manaCostModifier *= 1f - 0.06f * druidTalents.getOmenOfClarity();

            extraCritPercent += 5f * druidTalents.getNaturesBounty();
            // Living Seed
            extraCritModifier = 0.1f * druidTalents.getLivingSeed() * calcOpts.getCurrent().getLivingSeedEfficiency() / 100f;

            minHeal *=
                    (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            maxHeal *=
                    (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            coefDH *=
                    (1f + 0.04f * druidTalents.getEmpoweredRejuvenation()) *
                            (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            periodicTick *=
                    (1f + 0.01f * druidTalents.getGenesis() + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            coefHoT *=
                    (1f + 0.04f * druidTalents.getEmpoweredRejuvenation()) *
                            (1f + 0.01f * druidTalents.getGenesis() + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());
        }
    }

class Rejuvenation extends Spell {
        private float manaCostModifier = 1f;
        private float extraTicks = 0f;
        private boolean hasteTicks = false;
        private float periodicTickModifier = 1f;

        public Rejuvenation(rawr.base.character.Character character, Stats calculatedStats) {
            CalculationOptionsTree calcOpts = (CalculationOptionsTree) character.getCalculationOptions();

            // Base values
            castTimeBeforeHaste = 0f;
            coefHoT = 1.879f / 5;

            calculateTalents(character.getDruidTalents(), calcOpts);

            applyStats(calculatedStats);
        }

        @Override
        public void applyStats(Stats stats) {
            super.applyStats(stats);

            spellPower = stats.getSpellPower();

            manaCost = (0.18f * TreeConstants.BaseMana - stats.getSpellsManaReduction());
            manaCost *= manaCostModifier; // from talents
            manaCost -= stats.getReduceRejuvenationCost(); // Idol of Awakening (-106 Manacost)

            periodicTick = 338f; // 1690 / 5
            periodicTick *= periodicTickModifier; // from talents
            periodicTick += stats.getRejuvenationHealBonus(); // Idol of Pure Thoughts

            periodicTicks = 5f + extraTicks; // from talents

            // Tier 8 (4) SetBonus
            if (stats.getRejuvenationInstantTick() > 0.0f) {
                // Set AverageHealingwithCrit = PeriodicTick
                // Some talents doesn't apply to this instant tick, so it should actually be less
                // than the normal tick, hopefully small enough error
                minHeal = getPeriodicTick() * stats.getRejuvenationInstantTick();
                maxHeal = getPeriodicTick() * stats.getRejuvenationInstantTick();
                coefDH = 0.0f; // PeriodicTick already scaled by SpellPower, so don't scale again
                critModifier = 1f;
            } else {
                minHeal = 0f;
                maxHeal = 0f;
            }

            // Tier 9 (4) SetBonus
            critHoTPercent = stats.getSpellCrit() * stats.getRejuvenationCrit();
            // Should set critPercent = critHoTPercent; to allow instantTick to also be crittable,
            // but cannot have 4 piece setbonus simultaneously

            // Tier 10 (4) SetBonus
            if (stats.getRejuvJumpChance() > 0) {
                // chanceOncePerRejuv = (float)(1f - Math.Pow(1f - calculatedStats.RejuvJumpChance, periodicTicks));
                float chance = periodicTicks * stats.getRejuvJumpChance();
                float factor = 1f; // assume it doesn't consume existing buff, if it does then factor = 0.5f
                // assume it will jump multiple times
                periodicTicks *= (1f + factor * chance + factor * chance * chance + factor * chance * chance * chance);
                // only one jump: periodicTicks *= (1f + factor * chance);
            }

            if (hasteTicks) applyHasteToPeriodicTickTime();
        }

        private void calculateTalents(rawr.base.talents.DruidTalents druidTalents, CalculationOptionsTree calcOpts) {
            extraTicks += 1 * druidTalents.getNaturesSplendor();

            manaCostModifier *= 1 - 0.2f * druidTalents.getTreeOfLife() - 0.03f * druidTalents.getMoonglow();
            // 6% chance to get Omen of Clarity...
            manaCostModifier *= 1 - 0.06f * druidTalents.getOmenOfClarity();

            periodicTickModifier *=
                    (1 + 0.01f * druidTalents.getGenesis() +
                            0.05f * druidTalents.getImprovedRejuvenation() +
                            0.02f * druidTalents.getGiftOfNature()) *
                            (1 + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1 + 0.06f * druidTalents.getTreeOfLife());

            coefHoT *=
                    (1 + 0.04f * druidTalents.getEmpoweredRejuvenation()) *
                            (1 + 0.01f * druidTalents.getGenesis() +
                                    0.05f * druidTalents.getImprovedRejuvenation() +
                                    0.02f * druidTalents.getGiftOfNature()) *
                            (1 + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1 + 0.06f * druidTalents.getTreeOfLife());

            // Glyph of Rapid Rejuvenation
            if (druidTalents.isGlyphOfRapidRejuvenation()) {
                hasteTicks = true;
            }
        }
    }

class Lifebloom extends Spell {
        protected float idolHoTBonus = 0f;
        protected float stackScaling = 1.0f;
        protected float stackSize = 1.0f;
        protected float manaRefund = 0.0f;
        private float manaCostModifier = 1f;

        @Override
        public float getPeriodicTick() {
            return stackScaling * (periodicTick + (idolHoTBonus + spellPower) * coefHoT);
        }

        @Override
        public float getAverageHealing() {
            return stackSize * (extraHealing + (minHeal + maxHeal) / 2 + spellPower * coefDH);
        }

        @Override
        public float getManaCost() {
            return (super.getManaCost() - stackSize * manaRefund);
        }

        public Lifebloom(rawr.base.character.Character character, Stats stats) {
            CalculationOptionsTree calcOpts = (CalculationOptionsTree) character.getCalculationOptions();

            // Base values
            castTimeBeforeHaste = 0f;
            periodicTickTime = 1f;
            coefHoT = 0.6684f / 7f;

            minHeal = 776f;
            maxHeal = 776f;
            coefDH = 0.516f;

            periodicTick = 53f;
            periodicTicks = 7f;

            // Seems to apply before talents
            calculateTalents(character.getDruidTalents(), calcOpts);

            applyStats(stats);
        }

        public Lifebloom(rawr.base.character.Character character, Stats stats, int numStacks, boolean fastStack) {
            this(character, stats);

            float newPeriodicTicks = periodicTicks;

            if (numStacks == 1) {
                // Do nothing, already setup
            } else if (numStacks == 2) {
                if (!fastStack) {
                    // Slow LB stacking
                    newPeriodicTicks = periodicTicks * 2 - 1; // Double number of ticks, but lose 1
                    // N-1 ticks of 1 stack + N ticks of 2 stacks, averaged over total ticks
                    stackScaling = ((periodicTicks - 1) + 2 * periodicTicks) / newPeriodicTicks;
                } else {
                    // Fast LB stacking
                    newPeriodicTicks = periodicTicks + 1; // Stack every tick
                    // 1 ticks of 1 stack + N ticks of 2 stacks, averaged over total ticks
                    stackScaling = ((1) + 2 * periodicTicks) / newPeriodicTicks;
                }

                stackSize = 2.0f; // Bloom heal doubled

                periodicTicks = newPeriodicTicks;
                numberOfCasts = 2;
            } else if (numStacks == 3) {
                if (!fastStack) {
                    // Slow LB stacking
                    newPeriodicTicks = periodicTicks * 3 - 2; // Triple number of ticks, but lose 1 each time
                    // N-1 ticks of 1 stack + N -1 ticks of 2 stacks, averaged over total ticks
                    stackScaling = ((periodicTicks - 1) + 2 * (periodicTicks - 1) + 3 * periodicTicks) / newPeriodicTicks;
                } else {
                    // Fast LB stacking
                    newPeriodicTicks = periodicTicks + 2; // Stack every tick
                    // 1 ticks of 1 stack + 1 ticks of 2 stacks, averaged over total ticks
                    stackScaling = ((1) + 2 * (1) + 3 * periodicTicks) / newPeriodicTicks;
                }

                stackSize *= 3.0f; // Bloom heal trippled

                periodicTicks = newPeriodicTicks;

                numberOfCasts = 3;
            }
        }

        @Override
        public void applyStats(Stats stats) {
            super.applyStats(stats);
            spellPower = stats.getSpellPower();
            critPercent = stats.getSpellCrit();
            manaCost = 0.28f * TreeConstants.BaseMana - stats.getSpellsManaReduction();
            manaCost *= (1f - stats.getLifebloomCostReduction());
            manaCost *= numberOfCasts;
            manaCost *= manaCostModifier;
            manaRefund = 0.14f * TreeConstants.BaseMana - 0.5f * stats.getSpellsManaReduction();
            manaRefund *= (1f - stats.getLifebloomCostReduction());
            manaRefund *= numberOfCasts;
            manaRefund *= manaCostModifier;
            idolHoTBonus = stats.getLifebloomTickHealBonus(); // Idol of the Emerald Queen
        }

        private void calculateTalents(rawr.base.talents.DruidTalents druidTalents, CalculationOptionsTree calcOpts) {
            periodicTicks += 2f * druidTalents.getNaturesSplendor();

            gcdBeforeHaste -= 1.5f * 0.02f * druidTalents.getGiftOfTheEarthmother();

            manaCostModifier *= (1f - 0.2f * druidTalents.getTreeOfLife());

            // 6% chance to get Omen of Clarity...
            manaCostModifier *= 1f - 0.06f * druidTalents.getOmenOfClarity();

            periodicTick *=
                    (1f + 0.01f * druidTalents.getGenesis() + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            coefHoT *=
                    (1f + 0.04f * druidTalents.getEmpoweredRejuvenation()) *
                            (1f + 0.01f * druidTalents.getGenesis() + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter() * druidTalents.getTreeOfLife()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            minHeal *=
                    (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            maxHeal *=
                    (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            coefDH *=
                    (1f + 0.04f * druidTalents.getEmpoweredRejuvenation()) *
                            (1f + 0.02f * druidTalents.getGiftOfNature()) *
                            (1f + 0.02f * druidTalents.getMasterShapeshifter()) *
                            (1f + 0.06f * druidTalents.getTreeOfLife());

            if (druidTalents.isGlyphOfLifebloom()) {
                periodicTicks += 1f;
            }
        }
    }

