package rawr.models.dpsdk;

import rawr.base.character.CharacterClass;
import rawr.base.talents.DeathKnightTalents;
import rawr.base.items.Item;
import rawr.base.stats.StatConversion;
import rawr.base.stats.Stats;

public class Weapon {
    public float baseSpeed;
    public float baseDamage;
    /** Speed of the weapon after haste has been applied. */
    public float hastedSpeed;
    public float mitigation;
    public float effectiveExpertise;
    public float chanceDodged;
    /** Damage per second generated by the weapon after AP modifiers and haste. */
    public float DPS;
    /** Damage per hit generated by the weapon after AP modifiers. */
    public float damage;

    public Weapon(Item i, Stats stats, CalculationOptionsDPSDK calcOpts, DeathKnightTalents talents, float expertise) {
        if (stats == null || calcOpts == null) {
            return;
        }

        if (i == null) {
            i = new Item();
            i.setSpeed(2.0f);
            i.setMinDamage(0);
            i.setMaxDamage(0);
        }

        effectiveExpertise = expertise;
        float fightDuration = calcOpts.getFightLength() * 60;

        if (i == null) {
            return;
        }

        baseSpeed = i.getSpeed();
        baseDamage = (float) (i.getMinDamage() + i.getMaxDamage()) / 2f + stats.getWeaponDamage();

        // Attack Speed
        {
            hastedSpeed = baseSpeed / ((1f + (StatConversion.getHasteFromRating(stats.getHasteRating(), CharacterClass.DeathKnight))) * (1 + stats.getPhysicalHaste()));
            hastedSpeed /= 1f + 0.05f * (float) talents.getImprovedIcyTalons();
        }

        // Dodge
        {
            chanceDodged = StatConversion.WHITE_DODGE_CHANCE_CAP[calcOpts.getTargetLevel() - 80];
            chanceDodged -= StatConversion.getDodgeParryReducFromExpertise(effectiveExpertise);
            if (chanceDodged < 0f) {
                chanceDodged = 0f;
            }
        }

        // White Damage
        {
            // White damage per hit.  Basic white hits are use elsewhere.
            damage = baseDamage + (stats.getAttackPower() / 14.0f) * baseSpeed;
            DPS = damage / hastedSpeed;
        }
    }
}
